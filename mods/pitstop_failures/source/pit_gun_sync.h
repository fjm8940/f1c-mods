#pragma once

#include <cctype>
#include <cmath>
#include <cstdint>
#include <cstring>
#include "f1c_pit_crew.h"

/* Wheel-gun audio follows the visible gun. The game plays each crew .ANM 1:1
 * from its script offset (baseStart), starting at the channel's absolute
 * start time, which PitStopOperationTimer 0x4A6340 sets when the stop begins
 * (channel = {start, end, 1/len, baseStart, baseEnd, ?, event}, start/end in
 * seconds since the stop began).
 * A burst plays when the gun comes to rest at the nut, for as long as it
 * stays there. Evidence and derivation:
 * trials/wheelgun-anim-2026-09-28/README.md. */

struct PitGunContact { float at, dwell; };  /* animation seconds */

/* Generated by tools/wheelgun_anim_contacts.py from the stock
 * Pits\Normal\pitanims.mas; Pits\Left is identical. Full-reach arrivals only
 * (the rear track's partial pause 0.14 m short of the nut is not a contact).
 * Front guns use F0PWGUNAAA, rear guns F0PWGUNDAA. */
static const PitGunContact PIT_GUN_FRONT[2]={{3.193f,0.691f},{6.649f,2.140f}};
static const PitGunContact PIT_GUN_REAR[2] ={{1.975f,0.757f},{6.090f,0.856f}};

struct PitGunChannel {
    double start_abs=0,end_abs=0;
    float base_start=0,base_end=0;
    bool found=false;
};

static bool pit_gun_name_is_gun(const char *name) {
    const char *prefix="WHEELGUN";
    for(size_t i=0;prefix[i];i++)
        if(!name[i] || std::toupper((unsigned char)name[i])!=prefix[i])return false;
    return true;
}

static int pit_gun_corner(const char *name) {
    char upper[F1C_PIT_CREW_NAME_SIZE]{};
    for(size_t i=0;i+1<sizeof upper && name[i];i++)
        upper[i]=(char)std::toupper((unsigned char)name[i]);
    return f1c_pit_crew_corner(upper);
}

/* Read-only: first channel of each corner's WHEELGUN actor. Returns the
 * number of corners found. Uses the reviewed crew layout from
 * f1c_pit_crew.h (crew at vehicle+0x32D4, 120-byte actors, 28-byte
 * channels) and adds the absolute window at channel +0/+4. */
static int pit_gun_channels_read(F1CPitCrewRead read,uintptr_t vehicle,PitGunChannel out[4]) {
    for(int i=0;i<4;i++)out[i]=PitGunChannel{};
    uint32_t crew=0,array=0,count=0;
    if(!f1c_pit_crew_read_at(read,vehicle,0x32d4u,&crew,sizeof crew) || !crew ||
       !f1c_pit_crew_read_at(read,crew,0x0cu,&count,sizeof count) ||
       !f1c_pit_crew_read_at(read,crew,0x10u,&array,sizeof array) ||
       !array || !count || count>F1C_PIT_CREW_MAX_ACTORS)return 0;
    int found=0;
    for(uint32_t i=0;i<count;i++) {
        const size_t offset=(size_t)i*120u;
        uint32_t name_ptr=0,channel_ptr=0,channels=0;
        if(!f1c_pit_crew_read_at(read,array,offset+100u,&name_ptr,sizeof name_ptr) ||
           !f1c_pit_crew_read_at(read,array,offset+112u,&channels,sizeof channels) ||
           !f1c_pit_crew_read_at(read,array,offset+116u,&channel_ptr,sizeof channel_ptr) ||
           !name_ptr || !channels || channels>32 || !channel_ptr)continue;
        char name[F1C_PIT_CREW_NAME_SIZE]{};
        bool terminated=false;
        for(size_t j=0;j+1<sizeof name;j++) {
            if(!f1c_pit_crew_read_at(read,name_ptr,j,&name[j],1))break;
            if(!name[j]){terminated=true;break;}
            if((unsigned char)name[j]<32 || (unsigned char)name[j]>126)break;
        }
        if(!terminated || !pit_gun_name_is_gun(name))continue;
        int corner=pit_gun_corner(name);
        if(corner<0 || out[corner].found)continue;
        float window[5]{};
        if(!f1c_pit_crew_read_at(read,channel_ptr,0,window,sizeof window))continue;
        out[corner].start_abs=window[0];out[corner].end_abs=window[1];
        out[corner].base_start=window[3];out[corner].base_end=window[4];
        out[corner].found=true;found++;
    }
    return found;
}

/* The channel window is on the stop's own clock: seconds since the stop
 * began (live 2026-09-28, player stop at sim 30.28: FL/FR/RL/RR starts
 * 4.60/4.73/5.97/4.83, each window exactly the script length). A channel
 * belongs to this stop only if it is finite, starts within the stop and has
 * the script's own length. */
static bool pit_gun_channel_plausible(const PitGunChannel &c,double stop_start) {
    if(!c.found || !std::isfinite(c.start_abs) || !std::isfinite(c.end_abs) ||
       !std::isfinite(c.base_start) || !std::isfinite(c.base_end) ||
       !std::isfinite(stop_start))return false;
    double length=(double)c.base_end-c.base_start;
    if(c.base_start<0 || c.base_start>5 || length<=1 || length>15)return false;
    if(c.start_abs<0 || c.start_abs>30)return false;
    return std::fabs((c.end_abs-c.start_abs)-length)<0.05;
}

/* Sim time of each contact for one corner. */
static bool pit_gun_contact_times(const PitGunChannel &c,int corner,double stop_start,
                                  double at[2],float dwell[2]) {
    if(corner<0 || corner>3)return false;
    const PitGunContact *track=corner<2?PIT_GUN_FRONT:PIT_GUN_REAR;
    for(int k=0;k<2;k++) {
        if(track[k].at<c.base_start || track[k].at>c.base_end)return false;
        at[k]=stop_start+c.start_abs+((double)track[k].at-c.base_start);
        dwell[k]=track[k].dwell;
    }
    return true;
}

/* Clip choice. 0 = "BRRRRT, BRRRRT", 1 = short "BRT BRT", 2 = "BR-RRR".
 * Normal work: the longest clip that ends before the gun leaves the nut.
 * A faulty gun stutters: the short double burst. Missing clips are skipped. */
static int pit_gun_pick_wav(const float seconds[3],float dwell,bool faulty) {
    if(faulty && seconds[1]>0)return 1;
    int best=-1,shortest=-1;
    for(int i=0;i<3;i++) {
        if(seconds[i]<=0)continue;
        if(shortest<0 || seconds[i]<seconds[shortest])shortest=i;
        if(seconds[i]<=dwell && (best<0 || seconds[i]>seconds[best]))best=i;
    }
    return best>=0?best:shortest;
}

/* Lollipop: the LOLLIPOP_UP track (Normal F0PLPOPBAA, Left F0PLPOPDAA,
 * script offset 0.0) spins the board from BRAKES to 1ST GEAR, holds, then
 * lifts. Edge-on (90 degrees) at 0.165 s in both tracks; generated by
 * tools/wheelgun_anim_contacts.py --lollipop. */
static const float PIT_LOLLIPOP_TURN=0.165f;

/* Read-only: the LOLLIPOP actor's UP channel (offset near 0, the long one). */
static bool pit_lollipop_channel_read(F1CPitCrewRead read,uintptr_t vehicle,PitGunChannel *out) {
    *out=PitGunChannel{};
    uint32_t crew=0,array=0,count=0;
    if(!f1c_pit_crew_read_at(read,vehicle,0x32d4u,&crew,sizeof crew) || !crew ||
       !f1c_pit_crew_read_at(read,crew,0x0cu,&count,sizeof count) ||
       !f1c_pit_crew_read_at(read,crew,0x10u,&array,sizeof array) ||
       !array || !count || count>F1C_PIT_CREW_MAX_ACTORS)return false;
    for(uint32_t i=0;i<count;i++) {
        const size_t offset=(size_t)i*120u;
        uint32_t name_ptr=0,channel_ptr=0,channels=0;
        if(!f1c_pit_crew_read_at(read,array,offset+100u,&name_ptr,sizeof name_ptr) ||
           !f1c_pit_crew_read_at(read,array,offset+112u,&channels,sizeof channels) ||
           !f1c_pit_crew_read_at(read,array,offset+116u,&channel_ptr,sizeof channel_ptr) ||
           !name_ptr || !channels || channels>32 || !channel_ptr)continue;
        char name[F1C_PIT_CREW_NAME_SIZE]{};
        bool terminated=false;
        for(size_t j=0;j+1<sizeof name;j++) {
            if(!f1c_pit_crew_read_at(read,name_ptr,j,&name[j],1))break;
            if(!name[j]){terminated=true;break;}
            name[j]=(char)std::toupper((unsigned char)name[j]);
        }
        if(!terminated || std::strcmp(name,"LOLLIPOP")!=0)continue;
        for(uint32_t j=0;j<channels;j++) {
            float window[5]{};
            if(!f1c_pit_crew_read_at(read,channel_ptr,(size_t)j*28u,window,sizeof window))continue;
            if(!(window[3]>=0 && window[3]<0.5f && window[4]-window[3]>5))continue;
            out->start_abs=window[0];out->end_abs=window[1];
            out->base_start=window[3];out->base_end=window[4];out->found=true;
            return true;
        }
        return false;
    }
    return false;
}

/* Sim time the board shows 1ST GEAR, or a negative value when the channel
 * is not this stop's (stop-relative start 0..120 s, exact script length). */
static double pit_lollipop_gear_time(const PitGunChannel &c,double stop_start) {
    if(!c.found || !std::isfinite(c.start_abs) || !std::isfinite(c.end_abs) ||
       !std::isfinite(c.base_start) || !std::isfinite(c.base_end) ||
       !std::isfinite(stop_start))return -1;
    double length=(double)c.base_end-c.base_start;
    if(c.start_abs<0 || c.start_abs>120 || length<=5 || length>15 ||
       std::fabs((c.end_abs-c.start_abs)-length)>=0.05 ||
       PIT_LOLLIPOP_TURN<c.base_start)return -1;
    return stop_start+c.start_abs+((double)PIT_LOLLIPOP_TURN-c.base_start);
}
