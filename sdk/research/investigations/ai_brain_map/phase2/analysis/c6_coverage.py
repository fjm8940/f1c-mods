#!/usr/bin/env python
"""C6 - recompute COVERAGE.md for AI Brain ABI v1.1.

Reads: ai_brain_abi_v1.json, ai_brain_abi_v1_1.json, phase2/ABI_GAPS.csv,
phase2/abi_v1_1_names.json, phase2/WRITER_CENSUS.csv, the corpus cache in
%TEMP%\\ai_brain_phase2 (for the function-coverage counts).
Writes: phase2/COVERAGE.md (v1.1 numbers). No other file is touched.
"""
from __future__ import annotations

import csv
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
AI = REPO / "investigations" / "ai_brain_map"
PH2 = AI / "phase2"
CACHE = Path(os.environ["TEMP"]) / "ai_brain_phase2"
CLAUDE_DOC54 = {"AIMainUpdate", "sub_426430", "sub_426100", "AISteeringCorrection",
                "SteeringAngleController", "sub_4258C0"}


def main() -> int:
    v1 = json.load(open(AI / "ai_brain_abi_v1.json", encoding="utf-8"))
    v11 = json.load(open(AI / "ai_brain_abi_v1_1.json", encoding="utf-8"))
    gaps = list(csv.DictReader(open(PH2 / "ABI_GAPS.csv", encoding="utf-8")))
    names = json.load(open(PH2 / "abi_v1_1_names.json", encoding="utf-8"))["fields"]
    census = list(csv.DictReader(open(PH2 / "WRITER_CENSUS.csv", encoding="utf-8")))

    v1_decs = {f["dec"] for f in v1["fields"]
               if f["base"] == "veh" and 0x3D00 <= f["dec"] <= 0x48C0}
    prop_decs = {int(g["dec"]) for g in gaps if g["in_proposal"] == "yes"}
    open_decs = {int(g["dec"]) for g in gaps if g["in_proposal"] == "no"}
    named = {n["dec"] for n in names}
    duplicates = prop_decs - named  # covered by v1 array fields (stride)
    universe = v1_decs | prop_decs
    uncovered = prop_decs - named - duplicates
    v11_decs = {f["dec"] for f in v11["fields"] if f["base"] == "veh"}
    assert uncovered == set(), "v1.1 missed proposal decs: %s" % uncovered
    assert named <= v11_decs, "names file decs missing from v1.1"
    pct = 100.0 * len((v1_decs | named | duplicates) & universe) / len(universe)

    # function coverage from the cached call graph
    calls = [json.loads(l) for l in open(CACHE / "all_calls.jsonl", encoding="utf-8")]
    func_lines = json.load(open(CACHE / "func_lines.json", encoding="utf-8"))
    mapped = set(CLAUDE_DOC54)
    for p in list(AI.glob("map_*.md")) + list((PH2 / "maps").glob("map_*.md")):
        mapped.add(p.stem[4:].replace("_part1", "").replace("_part2", "")
                   .replace("_part3", "").replace("_part4", "").replace("_part5", ""))
    second = set()
    for c in calls:
        if c["func"] in mapped and c["expr"] in func_lines and c["expr"] not in mapped:
            second.add(c["expr"])
    one_level = {c["expr"] for c in calls if c["func"] == "AIMainUpdate"} & set(func_lines)
    one_level -= mapped

    lines = []
    lines.append("# COVERAGE - AI brain phase 2 census (recomputed for ABI v1.1, 2026-10-02)\n")
    lines.append("Generated by `phase2/analysis/c6_coverage.py` from `ai_brain_abi_v1.json`,")
    lines.append("`ai_brain_abi_v1_1.json`, `phase2/ABI_GAPS.csv`, `phase2/abi_v1_1_names.json`")
    lines.append("and the read-only corpus cache in `%TEMP%\\ai_brain_phase2`. The C4 numbers are")
    lines.append("historical; this file reflects the reviewed v1.1 merge.\n")
    lines.append("## Vehicle-offset coverage (nominated range 0x3D00..0x48C0)\n")
    lines.append("- base-resolved vehicle offsets read/written by the mapped AI set: **%d**" % len(universe))
    lines.append("- in AI Brain ABI v1.1 (`ai_brain_abi_v1_1.json`): **%d**" % len(v1_decs | named))
    lines.append("- covered by v1 array fields via stride (the 9 excluded proposal duplicates): **%d**" % len(duplicates))
    lines.append("- base-open offsets excluded from the registry (waypoint/surface objects): **%d**" % len(open_decs))
    lines.append("- coverage of the base-resolved universe: **%.1f%%**\n" % pct)
    lines.append("The nine stride-covered offsets are 0x41B8, 0x41EC, 0x41FC, 0x4230, 0x4240,")
    lines.append("0x4274, 0x4284, 0x42B8, 0x42C8 (opponent slots 1..4 of the two v1 arrays).")
    lines.append("The six base-open offsets are the TireForce/TireForceSolver/AerodynamicForceCalc")
    lines.append("`this` fields; their base is not the vehicle.\n")
    lines.append("## Function coverage (unchanged from C4)\n")
    lines.append("- phase-1 maps: 19; phase-2 maps: 64; doc-54-only functions: 6.")
    lines.append("- direct callees of AIMainUpdate without a map: %d%s" % (
        len(one_level), (": " + ", ".join(sorted(one_level))) if one_level else ""))
    lines.append("- second-level callees of mapped functions without a map (with a `.c` file): **%d**" % len(second))
    lines.append("  (%s)" % ", ".join(sorted(second)[:25]))
    lines.append("- math/compiler artifacts without a `.c` file are excluded (JUMPOUT, LOBYTE,")
    lines.append("  LODWORD, atan2, cos, fabs, sin, sqrt).\n")
    lines.append("## Writer census summary (61 v1 fields, whole functions/ corpus)\n")
    inside = len({r["field_id"] for r in census if r["in_ai_mapped_set"] == "yes"})
    none_writers = [f["id"] for f in v1["fields"]
                    if not any(r["field_id"] == f["id"] and r["access"] == "W" for r in census)]
    outside = sorted({r["function"] for r in census
                      if r["access"] == "W" and r["in_ai_mapped_set"] == "no"})
    lines.append("- v1 fields with at least one mapped-AI reader or writer: %d/61" % inside)
    lines.append("- v1 fields with no exact-offset writer: %s" % (", ".join(none_writers) or "none"))
    lines.append("  (writes go through shifted bases or indexed/pointer stores.)")
    lines.append("- writers outside the mapped set:\n  %s\n" % ", ".join(outside))
    lines.append("## Still unknown\n")
    lines.append("- the %d base-open force/waypoint `this` offsets (not vehicles);" % len(open_decs))
    lines.append("- the %d second-level unmapped callees;" % len(second))
    lines.append("- the indirect writers of: %s;" % (", ".join(none_writers) or "none"))
    lines.append("- the writers of 0x4408 and 0x44B4 are still pointer-based (doc 54 section 7).")
    out = PH2 / "COVERAGE.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s" % out)
    print("universe %d; v1.1 covered %d (+%d stride); base-open %d; coverage %.1f%%" % (
        len(universe), len(v1_decs | named), len(duplicates), len(open_decs), pct))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
