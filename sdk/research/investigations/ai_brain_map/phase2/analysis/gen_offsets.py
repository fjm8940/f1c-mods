#!/usr/bin/env python
"""Phase-2 helper: generate offsets_<Name>.csv for the C3 target set.

Targets = every one-level callee (with a functions/*.c file) of AIMainUpdate,
the phase-1 mapped functions and Claude's doc-54 functions, that has no
map_*.md yet, plus AICollision_004bef60. Math/compiler artifacts without a .c
file are reported, not mapped. Output: phase2/maps/offsets_<Name>.csv and
phase2/maps/unmatched_<Name>.txt, plus phase2/maps/TARGETS.md.

Read-only over functions/; writes only inside phase2/maps/.
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(REPO / "investigations" / "ai_brain_map"))
import extract_offsets  # noqa: E402

MAPS = HERE.parent / "maps"
FUNCTIONS = REPO / "functions"
CSV_FIELDS = extract_offsets.FIELDS

MAPPED_PHASE1 = {
    "AIAbility", "AIComputePassScore", "AIOvertake", "AIRacingLine",
    "AIRacingLinePathFollowing", "AISteering", "AISteeringRacingLineCorrection",
    "AerodynamicForceCalc", "BrakeThermalModel",
    "OpponentProximityScanTeamRecognition", "Overtaking",
    "PhysicsGearShiftLogicWithThresholds", "TireForce", "TireForceSolver",
    "TireGripCoefficient",
}
CLAUDE_DOC54 = {"AIMainUpdate", "sub_426430", "sub_426100", "AISteeringCorrection",
                "SteeringAngleController", "sub_4258C0"}
EXTRA = {"AICollision"}  # AICollision_004bef60, named by the handoff


def source_index() -> dict[str, Path]:
    out = {}
    for p in FUNCTIONS.glob("*.c"):
        m = re.match(r"^(.*)_[0-9a-fA-F]{8}$", p.stem)
        out[m.group(1) if m else p.stem] = p
    return out


def get_calls() -> dict[str, set[str]]:
    rows = list(csv.DictReader(open(REPO / "investigations" / "ai_brain_map" / "offsets_ALL.csv",
                                      encoding="utf-8", newline="")))
    calls: dict[str, set[str]] = {}
    for r in rows:
        if r["access"] == "CALL":
            calls.setdefault(r["func"], set()).add(r["expr"])
    return calls


def main() -> int:
    MAPS.mkdir(parents=True, exist_ok=True)
    sources = source_index()
    calls = get_calls()
    mapped = {re.sub(r"_part\d+$", "", p.stem[4:])
              for p in (REPO / "investigations" / "ai_brain_map").glob("map_*.md")}
    all_callees: dict[str, set[str]] = {}
    for fn in MAPPED_PHASE1 | CLAUDE_DOC54:
        for c in calls.get(fn, ()):
            all_callees.setdefault(c, set()).add(fn)
    targets = {c for c in all_callees if c not in mapped and c not in CLAUDE_DOC54
               and c in sources}
    targets |= {c for c in EXTRA if c in sources}
    missing_files = sorted(c for c in all_callees if c not in sources and c not in mapped)

    manifest = ["# C3 target set (generated by analysis/gen_offsets.py)", ""]
    manifest.append("One-level callees of the phase-1 mapped set + doc-54 set with no map yet.")
    manifest.append("")
    manifest.append("| map | source file | called by |")
    manifest.append("|---|---|---|")
    total_rows = 0
    for name in sorted(targets):
        src = sources[name]
        rows = extract_offsets.extract_file(src, MAPS / ("unmatched_%s.txt" % name))
        for row in rows:
            if row["dec"].startswith("-"):
                row["hex"] = ""
        with open(MAPS / ("offsets_%s.csv" % name), "w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=CSV_FIELDS, lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
        total_rows += len(rows)
        manifest.append("| map_%s.md | %s | %s |" % (
            name, src.name, ", ".join(sorted(all_callees.get(name, ())))))
    manifest.append("")
    manifest.append("Not mappable (no functions/*.c): %s" % ", ".join(missing_files))
    (MAPS / "TARGETS.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print("targets: %d, csv rows: %d, not mappable: %d" % (
        len(targets), total_rows, len(missing_files)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
