#!/usr/bin/env python3
"""
make_release.py  -  produce a hardened production source from gr44.c

The debug build leaks its entire algorithm through log strings ("un-retired %d
cars for the restart grid", "arm ... retire on reaching their own pit box",
literal offsets, etc). This transform strips every diagnostic string WITHOUT
touching game logic:

  1. log_w(...)            -> compiled out via macro (literal never emitted)
  2. wsprintfA(buf, "...") -> replaced by (void)0;  EXCEPT the one real HUD
                             string ("RACE RESTART IN %d"), which is on-screen
                             text and reveals nothing.
  3. the hardcoded absolute log path in DllMain is removed.
  4. one intentional credit watermark is inserted.

Control flow is preserved (log_w becomes ((void)0), so `if(x) log_w(); else
log_w();` stays valid). Behavior is identical; only the confession is gone.
"""
import re, sys, pathlib

SRC = pathlib.Path(__file__).with_name("gr44.c")
DST = pathlib.Path(__file__).with_name("redflag.c")

text = SRC.read_text(encoding="utf-8", errors="replace")

# --- 2. blank every wsprintfA(...) statement except the HUD countdown one ----
def find_stmt_end(s, start):
    """start = index of 'wsprintfA'; return index just past the closing ');'"""
    i = s.index("(", start)
    depth = 0
    instr = False
    esc = False
    while i < len(s):
        c = s[i]
        if instr:
            if esc: esc = False
            elif c == "\\": esc = True
            elif c == '"': instr = False
        else:
            if c == '"': instr = True
            elif c == "(": depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    # expect trailing ';'
                    j = i + 1
                    while j < len(s) and s[j] in " \t": j += 1
                    if j < len(s) and s[j] == ";": return j + 1
                    return i + 1
        i += 1
    return len(s)

out = []
idx = 0
for m in re.finditer(r"\bwsprintfA\b", text):
    start = m.start()
    if start < idx:
        continue
    end = find_stmt_end(text, start)
    stmt = text[start:end]
    out.append(text[idx:start])
    if "RACE RESTART IN %d" in stmt:      # the only real on-screen string
        out.append(stmt)
    else:
        out.append("(void)0;")
    idx = end
out.append(text[idx:])
text = "".join(out)

# --- 3. drop the hardcoded absolute log path -------------------------------
text = re.sub(r'strcpy\(g_log,\s*"[^"]*"\);', "(void)g_log;", text)

# --- 1. + 4. inject release macros and watermark just after the includes ----
anchor = "#include <mmsystem.h>\n"
inject = anchor + """
/* ------------------------------------------------------------------ *
 *  PRODUCTION BUILD - generated by make_release.py from gr44.c        *
 *  All diagnostic logging is compiled out; do not edit this file by   *
 *  hand, edit gr44.c and regenerate.                                  *
 * ------------------------------------------------------------------ */
#define RF_RELEASE 1

/* Credit watermark - the ONE string intentionally left in the binary. */
__attribute__((used))
volatile const char RF_SIGNATURE[] =
    "F1 Challenge RED FLAG mod - by Matias - "
    "please keep this credit if you redistribute";

/* log_w() textually discards its argument, so no log literal is emitted and
 * control flow (if/else without braces) stays valid. */
#undef  log_w
#define log_w(s) ((void)0)
"""
# place the macros AFTER log_w is declared? No - we #define after the static
# definition so the definition itself is untouched but every CALL is replaced.
# Insert immediately before the first use is simplest: right after log_w's own
# definition. Find it.
text = text.replace(anchor, anchor, 1)  # noop, keep anchor

logw_start = text.index("static void log_w(const char* s) {")
# find the brace that closes the FUNCTION, not the inner if-block
i = text.index("{", logw_start)
depth = 0
while i < len(text):
    if text[i] == "{": depth += 1
    elif text[i] == "}":
        depth -= 1
        if depth == 0:
            break
    i += 1
logw_def_end = i + 1
macros = """

/* ---- PRODUCTION BUILD (generated by make_release.py from gr44.c) ----
 * Diagnostic logging compiled out below this point. Edit gr44.c, regenerate. */
#define RF_RELEASE 1
__attribute__((used))
volatile const char RF_SIGNATURE[] =
    "F1 Challenge RED FLAG mod - by Matias - "
    "please keep this credit if you redistribute";
#undef  log_w
#define log_w(s) ((void)0)
"""
text = text[:logw_def_end] + macros + text[logw_def_end:]

# keep the watermark from being dead-stripped: reference it once in DllMain
text = text.replace(
    "DisableThreadLibraryCalls(h);",
    "DisableThreadLibraryCalls(h);\n        "
    "{ volatile char _rfk = RF_SIGNATURE[0]; (void)_rfk; }",
    1)

DST.write_text(text, encoding="utf-8")
print(f"wrote {DST} ({len(text)} bytes)")
