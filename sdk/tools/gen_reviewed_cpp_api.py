#!/usr/bin/env python3
"""Generate source-like C++ wrappers for reviewed function ABIs only."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "tools" / "sdk"
catalogue = json.loads((SDK / "f1c_sdk.json").read_text(encoding="utf-8"))

def ctype(value):
    return value.replace("F1CVehicle*", "::F1CVehicle*").replace(
        "F1CPitMachine*", "::F1CPitMachine*")

reviewed = [(name, fn) for name, fn in catalogue["functions"].items()
            if fn.get("trust") in ("FACT", "CONFIRMED")]
reviewed.sort(key=lambda item: int(item[1]["address"]))
lines = [
    "/* Generated by tools/gen_reviewed_cpp_api.py. Reviewed ABIs only. */",
    "#pragma once", "#include <cstdint>", '#include "f1c_vehicle_struct.h"',
    '#include "f1c_pit_struct.h"', '#include "f1c_runtime.h"', "",
    "#if defined(_MSC_VER)", "#define F1C_API_THISCALL __thiscall",
    "#define F1C_API_STDCALL __stdcall",
    "#elif defined(__GNUC__) && defined(__i386__)",
    "#define F1C_API_THISCALL __attribute__((thiscall))",
    "#define F1C_API_STDCALL __attribute__((stdcall))",
    "#else", "#define F1C_API_THISCALL", "#define F1C_API_STDCALL", "#endif", "",
    "namespace f1c { namespace reviewed { namespace game_thread {", "",
]
for name, fn in reviewed:
    safe_name = re.sub(r"\W", "_", name)
    ret = ctype(fn.get("return", "void"))
    params = fn.get("parameters", [])
    declarations = ", ".join(f"{ctype(p['type'])} {p['name']}" for p in params)
    arguments = ", ".join(p["name"] for p in params)
    convention = {"thiscall": "F1C_API_THISCALL ",
                  "stdcall": "F1C_API_STDCALL "}.get(fn.get("calling_convention"), "")
    pointer_args = ", ".join(ctype(p["type"]) for p in params)
    lines.append(f"using {safe_name}Fn = {ret} ({convention}*)({pointer_args});")
    lines.append(f"inline {ret} {safe_name}({declarations})")
    lines.append("{")
    call = f"reinterpret_cast<{safe_name}Fn>(0x{int(fn['address']):08X}u)({arguments})"
    lines.append(f"    {'return ' if ret != 'void' else ''}{call};")
    lines.append("}")
    lines.append("")
lines += ["}}} // namespace f1c::reviewed::game_thread", "",
          "#undef F1C_API_THISCALL", "#undef F1C_API_STDCALL", ""]
(SDK / "f1c_reviewed_api.hpp").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"reviewed C++ API: {len(reviewed)} wrappers -> tools/sdk/f1c_reviewed_api.hpp")
