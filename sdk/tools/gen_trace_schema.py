#!/usr/bin/env python3
"""Generate compact runtime field descriptors from trusted SDK vehicle data."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / "tools" / "sdk"
source = json.loads((SDK / "f1c_sdk.json").read_text(encoding="utf-8"))
type_map = {
    "uint8_t": ("F1C_TRACE_U8", 1),
    "int32_t": ("F1C_TRACE_I32", 4),
    "float": ("F1C_TRACE_F32", 4),
    "void*": ("F1C_TRACE_PTR32", 4),
}
fields = []
for name, field in source["vehicle_fields"].items():
    if field.get("trust") not in ("FACT", "CONFIRMED"):
        continue
    mapped = type_map.get(field.get("ctype"))
    if not mapped:
        continue
    fields.append((int(field["offset"], 16), name, *mapped,
                   field.get("trust", ""), field.get("semantic", "state")))
fields.sort()

lines = [
    "/* Generated by tools/gen_trace_schema.py from trusted canonical fields. */",
    "#pragma once", "#include <stdint.h>", "",
    "typedef enum F1CTraceFieldType {",
    "    F1C_TRACE_U8, F1C_TRACE_I32, F1C_TRACE_F32, F1C_TRACE_PTR32",
    "} F1CTraceFieldType;", "",
    "typedef struct F1CTraceFieldDesc {",
    "    const char *name;", "    uint16_t offset;", "    uint8_t size;",
    "    uint8_t type;", "    const char *trust;", "    const char *semantic;",
    "} F1CTraceFieldDesc;", "",
    f"#define F1C_TRACE_FIELD_COUNT {len(fields)}", "",
    "static const F1CTraceFieldDesc F1C_TRACE_VEHICLE_FIELDS[F1C_TRACE_FIELD_COUNT] = {",
]
for offset, name, enum_name, size, trust, semantic in fields:
    lines.append(f'    {{"{name}", 0x{offset:04X}, {size}, {enum_name}, "{trust}", "{semantic}"}},')
lines += ["};", ""]
(SDK / "f1c_trace_schema.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"trace schema: {len(fields)} trusted scalar vehicle fields -> tools/sdk/f1c_trace_schema.h")

