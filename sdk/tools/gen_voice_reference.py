"""tools/gen_voice_reference.py - build docs/56-voice-line-reference-map.md (2026-10-12).

One reference map for every commentary / pit-radio event id (eid):
eid -> SDT clip index -> clip name -> what the line says -> cooldown / blocked
-> work status. Sources, in priority order for the "says" column:

1. SPEC_EVF-008_*.md tables (hand-verified rows "| text | SDT | EID | verdict |";
   these resolve the clips whose SDT names are truncated to 15 characters,
   e.g. PWS_AIMECHPROB0 = AIMECHPROB01..09)
2. voice_browser.py DESCRIPTIONS (the owner's manual listening map, used by
   browse_voices.bat)
3. progress.json description

Event table: data/full_event_dump.json. Clip names: PC_RE_MAIN.SDT via
voice_browser.parse_sdt (read-only). Re-run after any of these change:

    python -B tools/gen_voice_reference.py
"""

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # f1c_ida_decompiled
EVF = os.path.join(ROOT, "mods", "extended_vanilla_features")     # preserved tree, read-only
OUT = os.path.join(ROOT, "docs", "56-voice-line-reference-map.md")
sys.path.insert(0, os.path.join(EVF, "tools"))
sys.dont_write_bytecode = True
import voice_browser as vb  # noqa: E402  (read-only import: DESCRIPTIONS, parse_sdt)

FLT_MAX = 3.0e38


def spec_rows():
    """{eid: (text, spec file)} from the EVF-008 hand tables."""
    out = {}
    row = re.compile(r"^\|\s*([^|]+?)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|")
    for path in sorted(glob.glob(os.path.join(EVF, "docs", "SPEC_EVF-008_*.md"))):
        with open(path, encoding="utf-8") as f:
            for line in f:
                m = row.match(line)
                text = m.group(1) if m else ""
                # a row whose text is only a clip name says nothing new
                if m and not text.lower().startswith("clip") and " " in text:
                    out[int(m.group(3))] = (text, os.path.basename(path))
    # stated in EVF-008 B prose (section heading), not in a table row
    out.setdefault(208, ("smoke coming from engine (AI)", "SPEC_EVF-008_B_gearloss.md"))
    return out


def main():
    clips = vb.parse_sdt(vb.SDT_PATH)
    with open(vb.DUMP_PATH, encoding="utf-8") as f:
        events = json.load(f)["events"]
    with open(os.path.join(EVF, "data", "progress.json"), encoding="utf-8") as f:
        prog = json.load(f).get("clips", {})
    spec = spec_rows()

    rows = []
    for key in sorted(events, key=int):
        ev = events[key]
        eid = int(key)
        si = ev.get("sdt_index")
        name = (clips[si]["name"] if si is not None and 0 <= si < len(clips)
                else ev.get("clip_name")) or ""
        says, src = "", ""
        if eid in spec:
            says, src = spec[eid][0], "EVF-008"
        if not says and name:
            _k, d = vb.match_description(name)
            if d:
                says, src = d, "browser"
        p = prog.get(str(si), {}) if si is not None else {}
        if not says and p.get("description"):
            says, src = p["description"], "progress"
        cd = ev.get("cooldown")
        cd_txt = "FLT_MAX" if cd is not None and cd > FLT_MAX else (
            f"{cd:g}" if cd is not None else "-")
        rows.append((eid, si, name.replace("|", "/"), says.replace("|", "/"), src,
                     cd_txt, "yes" if ev.get("blocked") else "", p.get("status", "")))

    n_says = sum(1 for r in rows if r[3])
    lines = [
        "# 56 - Voice line reference map (commentary / pit radio eids)",
        "",
        "Generated by `tools/gen_voice_reference.py` "
        "(2026-10-12). Do not edit the table by hand: fix the source and re-run.",
        "",
        "Use this file to pick an eid before queueing a native line (record init `0x4144D0`, "
        "formatter `0x4144F0`, `InsertDriverTableEntry 0x418560` on `0x5EA618`; SDK "
        "`tools/sdk/f1c_pit_voice.h`). Third-person AI lines need the subject driver id "
        "`veh+0x489C` (as `sub_41AC50`).",
        "",
        "## Sources and trust",
        "",
        "- `says` source `EVF-008`: hand table in `mods/extended_vanilla_features/docs/"
        "SPEC_EVF-008_*.md` (owner listening / isolation tests). Highest trust; resolves "
        "clips whose SDT names are truncated to 15 characters (`PWS_AIMECHPROB0` = "
        "AIMECHPROB01..09, `PWS_AIMECHPROB1` = AIMECHPROB10..).",
        "- `browser`: `voice_browser.py` DESCRIPTIONS, the owner's manual map behind "
        "`tools/browse_voices.bat`. Matched by clip name, so a truncated name can match the "
        "wrong sibling: trust EVF-008 rows over it.",
        "- `progress`: `data/progress.json` description.",
        "- `cooldown` / `blocked`: `data/full_event_dump.json` (live event-table dump). "
        "FLT_MAX = never plays unless a mod clears it (gear_failure clears 80-93).",
        "- Empty `says` = not identified yet (listen in browse_voices.bat, add to "
        "DESCRIPTIONS or an EVF table, re-run).",
        "",
        "## Verified gearbox lines (quick map)",
        "",
        "| Line | eid | Evidence |",
        "|---|---|---|",
        "| player radio: lost 1st..7th gear | 80..86 | heard, isolation-injected 2026-07-30 (gear_failure EID_LOST) |",
        "| player radio: stuck in 1st..7th gear | 87..93 | heard 2026-07-30 (gear_failure EID_STUCK) |",
        "| AI: <driver> has lost 1st..6th gear | 201..206 | EVF-008 B table (owner) |",
        "| AI: <driver> has lost 7th gear | 209 | RE_OD_LOST_7 |",
        "| AI: periodically slowing down | 207 | EVF-008 B |",
        "| AI: smoke coming from engine | 208 | EVF-008 B; native `sub_41AC50(veh, 0)` |",
        "| AI: <driver> is stuck in 1st..6th gear | 212..217 | native `sub_41AC50(veh, 2)` table; 213 heard 2026-07-30 |",
        "| AI: <driver> is stuck in 7th gear | 211 | RE_OD_STUCK_7, native default case |",
        "",
        "Native AI gear emitter `sub_41AC50` runs only when SessionType == 7 (race), the "
        "commentary flag `0x7D0308` is set and level `0x7CF3C8` != 0.",
        "",
        f"## Full table ({len(rows)} eids, {n_says} identified)",
        "",
        "| eid | sdt | clip (SDT name) | says | source | cooldown s | blocked | status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(rows)} eids, {n_says} identified")


if __name__ == "__main__":
    main()
