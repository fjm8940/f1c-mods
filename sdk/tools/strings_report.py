"""strings_report.py — turn strings_index.json into the two naming oracles.

Reads   : strings_index.json   (produced by extract_strings.py, headless IDA)
Writes  : strings_modules.json  — original .cpp/.h source file -> functions that
                                  reference a string from it (module attribution)
          strings_tokens.json   — config-file token candidates -> the functions
                                  that compare/parse them (parser oracle)
          STRINGS_REPORT.md     — human/LLM-readable summary of both

Trust: extraction tier. Every mapping here is an IDA xref, not an inference.
The INTERPRETATION of a token (which struct offset it lands in) is NOT done here
— that stays a separate, evidenced step.

Usage: python tools/strings_report.py
"""
import io
import json
import os
import re
import collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IDX = os.path.join(ROOT, "strings_index.json")

# A path the compiler baked in, e.g. "D:\dev\F1_1999_2002\Source\hdvehicle.cpp".
SRC_RE = re.compile(r"([A-Za-z0-9_\-]+\.(?:cpp|cxx|c|hpp|h))\s*$", re.I)
PATHY = ("\\", "/")

# A config-file token: identifier-ish, no spaces, not a path, not a format string.
TOKEN_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{2,39}$")
SECTION_RE = re.compile(r"^\[[A-Z0-9_ ]{2,40}\]\s*$")
FILE_EXT_RE = re.compile(r"\.(?:hdv|aiw|rcd|tbc|gdb|plr|ini|cam|sfx|mas|veh|tga|gmt)\b", re.I)


def load():
    with io.open(IDX, encoding="utf-8") as f:
        return json.load(f)


def funcs_of(rec):
    """Every function reachable from a string record, code refs + table readers."""
    out = []
    for x in rec.get("code_xrefs", []):
        out.append((x["func"], x.get("func_name") or ""))
    for x in rec.get("data_xrefs", []):
        for r in x.get("readers", []):
            out.append((r["func"], r.get("func_name") or ""))
    return out


def build_modules(strings):
    """Original source-file attribution.

    MSVC bakes __FILE__ into asserts and error text, so a string like
    'D:\\dev\\F1_1999_2002\\Source\\hdvehicle.cpp' names the translation unit the
    referencing function was compiled from. That is a module map for free — the
    single strongest structural signal available for 7,143 otherwise anonymous
    functions.
    """
    mods = collections.defaultdict(lambda: {"strings": [], "functions": {}})
    for ea, rec in strings.items():
        s = rec["s"].strip()
        if not any(p in s for p in PATHY):
            continue
        m = SRC_RE.search(s)
        if not m:
            continue
        fname = m.group(1).lower()
        mods[fname]["strings"].append({"ea": ea, "s": s})
        for addr, name in funcs_of(rec):
            mods[fname]["functions"][addr] = name
    return mods


def build_tokens(strings):
    """Config-file token candidates and who reads them.

    F1C is half data-driven (hdv/aiw/rcd/tbc/gdb/plr). The parsers for those files
    live in the exe and compare incoming keys against literal token strings. A
    token plus the function that consumes it is the game naming its own field.
    Selection here is deliberately shallow and deterministic: shape of the string
    plus the presence of a consumer. Deciding which struct offset a token writes
    is a later, separately evidenced step.
    """
    toks = {}
    for ea, rec in strings.items():
        s = rec["s"].strip()
        consumers = funcs_of(rec)
        if not consumers:
            continue
        if SECTION_RE.match(s):
            kind = "section"
        elif FILE_EXT_RE.search(s):
            kind = "filespec"
        elif TOKEN_RE.match(s):
            kind = "token"
        else:
            continue
        seen = {}
        for addr, name in consumers:
            seen[addr] = name
        toks[ea] = {
            "s": s,
            "kind": kind,
            "consumers": [{"func": a, "func_name": n} for a, n in sorted(seen.items())],
        }
    return toks


def write_report(meta, mods, toks):
    lines = []
    lines.append("# STRINGS_REPORT — string-literal naming oracles")
    lines.append("")
    lines.append("Generated by `tools/strings_report.py` from `strings_index.json` "
                 "(`extract_strings.py`, headless IDA). **Extraction tier** — every "
                 "row below is an IDA xref, not an interpretation.")
    lines.append("")
    lines.append("| metric | value |")
    lines.append("|---|---|")
    for k in ("binary", "generated", "n_strings", "n_code_xrefs", "n_data_xrefs",
              "n_functions_with_strings", "n_orphans", "n_rejected_nontext_or_code"):
        lines.append("| %s | %s |" % (k, meta.get(k)))
    lines.append("| source files identified | %d |" % len(mods))
    lines.append("| token candidates | %d |" % len(toks))
    lines.append("")

    lines.append("## 1. Module map — original translation units")
    lines.append("")
    lines.append("MSVC baked `__FILE__` into asserts/error text, so these are the "
                 "real source filenames of the 2002 build. A function referencing "
                 "one of them was (almost certainly) compiled from it.")
    lines.append("")
    lines.append("| source file | strings | functions attributed |")
    lines.append("|---|---|---|")
    for name, d in sorted(mods.items(), key=lambda kv: -len(kv[1]["functions"])):
        lines.append("| `%s` | %d | %d |" % (name, len(d["strings"]), len(d["functions"])))
    lines.append("")

    by_kind = collections.Counter(v["kind"] for v in toks.values())
    lines.append("## 2. Config-token oracle")
    lines.append("")
    lines.append("Candidates by kind: " +
                 ", ".join("%s=%d" % kv for kv in sorted(by_kind.items())))
    lines.append("")
    lines.append("Full data in `strings_tokens.json`. Sample (token -> consumer):")
    lines.append("")
    lines.append("| token | kind | consumer |")
    lines.append("|---|---|---|")
    sample = sorted(toks.items(), key=lambda kv: kv[1]["s"].lower())[:60]
    for ea, v in sample:
        c = v["consumers"][0]
        lines.append("| `%s` | %s | `%s` |" % (v["s"], v["kind"],
                                               c["func_name"] or c["func"]))
    lines.append("")
    lines.append("**Next step (not done here):** for each token, read the consumer "
                 "function and record which struct offset the parsed value lands in. "
                 "A token name matched to an offset is the game naming its own field "
                 "— code + shipped data file = two independent sources = CONFIRMED "
                 "tier in `name_index.json`.")
    lines.append("")
    return "\n".join(lines)


def main():
    d = load()
    strings = d["strings"]
    mods = build_modules(strings)
    toks = build_tokens(strings)

    with io.open(os.path.join(ROOT, "strings_modules.json"), "w", encoding="utf-8") as f:
        json.dump(mods, f, indent=1, ensure_ascii=False, sort_keys=True)
    with io.open(os.path.join(ROOT, "strings_tokens.json"), "w", encoding="utf-8") as f:
        json.dump(toks, f, indent=1, ensure_ascii=False, sort_keys=True)
    with io.open(os.path.join(ROOT, "STRINGS_REPORT.md"), "w", encoding="utf-8") as f:
        f.write(write_report(d["_meta"], mods, toks))

    nfun = len(set(a for m in mods.values() for a in m["functions"]))
    print("[report] %d source files, %d functions attributed, %d token candidates"
          % (len(mods), nfun, len(toks)))


if __name__ == "__main__":
    main()
