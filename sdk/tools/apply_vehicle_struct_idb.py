"""
apply_vehicle_struct_idb.py — Import struct F1CVehicle into the IDB's Local Types.

Source: tools/sdk/f1c_vehicle_struct_ida.h (IDA-flavoured: no #include, native
type spellings), generated by gen_vehicle_struct_header.py from name_index.json.
The stdint flavour (f1c_vehicle_struct.h) is for compiling mods, NOT parse_decls.

Headless: idat.exe -A -L"idat_struct.log" -S"apply_vehicle_struct_idb.py" <i64>
Close the IDA GUI first (DB lock) — see RUNBOOK_SKELETON_BATCH.md convention.
MUST end in qexit(): without it idat hangs forever in autonomous mode.

Non-destructive: only adds/updates the F1CVehicle local type. Does NOT retype any
function's `this`/arg1 — do that per-function afterwards, once you're in there.

On failure the script BISECTS the member list and prints the first member that
breaks the parse, instead of reporting a bare failure count.
"""
import ida_typeinf
import ida_auto
import ida_loader
import ida_pro
import os
import re

IDA_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = os.path.join(IDA_ROOT, "tools", "sdk", "f1c_vehicle_struct_ida.h")
EXPECT_SIZE = 0x48C0


def log(msg):
    print(f"[struct] {msg}")


ida_auto.auto_wait()          # let autoanalysis settle before touching types
til = ida_typeinf.get_idati()

src = open(HDR, encoding="utf-8").read()
# member lines = indented decls; most carry a trailing "// 0xNNNN TRUST" comment,
# so match on the semicolon anywhere, not at end of line.
members = [ln for ln in src.splitlines()
           if ln.startswith("    ") and ";" in ln]
log(f"header {os.path.basename(HDR)}: {len(members)} member lines")


def try_parse(name, member_lines):
    """Parse a struct of the given members under a throwaway name.
    Returns (parsed_ok, size or None)."""
    body = "\n".join(member_lines)
    decl = f"struct {name} {{\n{body}\n}};\n"
    nfail = ida_typeinf.parse_decls(til, decl, None, ida_typeinf.HTI_DCL)
    tif = ida_typeinf.tinfo_t()
    got = tif.get_named_type(til, name)
    return (nfail == 0 and got), (tif.get_size() if got else None)


# --- control: prove parse_decls works at all in this build ---
ctl_ok, ctl_sz = try_parse("__F1CProbe", ["    int a;"])
log(f"control parse (int a): ok={ctl_ok} size={ctl_sz}")

# --- real import ---
nfail = ida_typeinf.parse_decls(til, src, None, ida_typeinf.HTI_DCL)
tif = ida_typeinf.tinfo_t()
ok = tif.get_named_type(til, "F1CVehicle")

if ok:
    size = tif.get_size()
    log(f"F1CVehicle imported: sizeof={size:#x} (expected {EXPECT_SIZE:#x})"
        f"{'  MISMATCH' if size != EXPECT_SIZE else ''}, failures={nfail}")
else:
    log(f"FAILED to register F1CVehicle (failures={nfail}) — bisecting members")
    # smallest prefix of members that fails to parse => first bad line
    bad = None
    for n in range(1, len(members) + 1):
        pok, _ = try_parse(f"__F1CBisect{n}", members[:n])
        if not pok:
            bad = n
            break
    if bad is None:
        log("every prefix parsed OK — failure is in the struct wrapper, not a member")
    else:
        log(f"first failing member is #{bad}: {members[bad - 1].strip()}")
        for ctx in range(max(0, bad - 3), min(len(members), bad + 2)):
            mark = ">>" if ctx == bad - 1 else "  "
            log(f"  {mark} [{ctx + 1:3d}] {members[ctx].strip()}")

ida_loader.save_database("", 0)
ida_pro.qexit(0 if ok else 1)
