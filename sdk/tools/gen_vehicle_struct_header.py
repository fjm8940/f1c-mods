"""
gen_vehicle_struct_header.py — Build a real C struct (not offset macros) for the
vehicle object, from the same verified source gen_sdk_from_index.py reads:
  name_index.json["vehicle_fields"]   trust-tiered, offset-keyed

Pure Python, no idapython — run this first to produce the header text.
Then apply_vehicle_struct_idb.py (headless, needs idat.exe) imports that text
into the IDB's Local Types so Hex-Rays shows F1CVehicle::field instead of
*(float*)(a1+0x453C) across every function that touches a vehicle.

Non-destructive: importing a local type does not touch any function's
existing decompilation until you explicitly retype an argument to it.

Output: tools/sdk/f1c_vehicle_struct.h
"""
import os
import json

IDA_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(IDA_ROOT, "tools", "sdk", "f1c_vehicle_struct.h")
# IDA variant: no #include (IDA's parser can't resolve system headers) and
# native IDA type spellings instead of stdint typedefs.
OUT_IDA = os.path.join(IDA_ROOT, "tools", "sdk", "f1c_vehicle_struct_ida.h")

# stdint spelling -> IDA-native spelling
IDA_TYPE = {"uint8_t": "unsigned __int8", "int8_t": "__int8",
            "uint16_t": "unsigned __int16", "int16_t": "__int16",
            "uint32_t": "unsigned int", "int32_t": "int",
            "float": "float", "double": "double",
            "char": "char", "void*": "void *"}

VEH_STRIDE = 0x48C0

ni = json.load(open(os.path.join(IDA_ROOT, "name_index.json"), encoding="utf-8"))
override_path = os.path.join(IDA_ROOT, "tools", "sdk", "f1c_sdk_overrides.json")
overrides = json.load(open(override_path, encoding="utf-8"))
vf = {hex(int(k, 16)): dict(v) for k, v in ni.get("vehicle_fields", {}).items()}
for off_hex, override in overrides.get("vehicle_fields", {}).items():
    key = hex(int(off_hex, 16))
    base = dict(vf.get(key, {}))
    base.update(override)
    vf[key] = base

C_TYPE = {"float": "float", "double": "double", "int": "int32_t",
          "int32": "int32_t", "uint32": "uint32_t", "int16": "int16_t",
          "uint16": "uint16_t", "int8": "int8_t", "uint8": "uint8_t",
          "byte": "uint8_t", "ptr": "void*", "string": "char", "embedded": "uint8_t"}
SIZE = {"float": 4, "double": 8, "int": 4, "int32": 4, "uint32": 4,
        "int16": 2, "uint16": 2, "int8": 1, "uint8": 1, "byte": 1,
        "ptr": 4, "string": 1, "embedded": 1}


def san(name):
    s = "".join(c if c.isalnum() or c == "_" else "_" for c in name.strip())
    return s if s and not s[0].isdigit() else "_" + s


entries = []
for off_hex, e in vf.items():
    off = int(off_hex, 16)
    t = e.get("type", "float")
    entries.append((off, san(e["name"]), t, e.get("trust", "GUESS"), e.get("note")))
entries.sort(key=lambda x: x[0])

lines = [
    "// f1c_vehicle_struct.h — generated by gen_vehicle_struct_header.py. DO NOT EDIT.",
    "// Source: name_index.json + reviewed tools/sdk/f1c_sdk_overrides.json.",
    "// Trust tags: FACT=poke-proven CONFIRMED=2-source DERIVED=lead(verify first) GUESS=unverified",
    "// Apply to the IDB with apply_vehicle_struct_idb.py (headless idat.exe run).",
    "#pragma once",
    "#include <stdint.h>",
    "",
    "struct F1CVehicle {",
]

cursor = 0
gap_n = 0
for i, (off, name, t, trust, note) in enumerate(entries):
    if off < cursor:
        # overlapping/duplicate-name field at same offset as a prior one — skip struct
        # member (name index sometimes lists the same offset twice under aliases)
        continue
    if off > cursor:
        gap_n += 1
        lines.append(f"    uint8_t gap_{cursor:04X}[0x{off - cursor:X}];")
    ctype = C_TYPE.get(t, "float")
    nxt = entries[i + 1][0] if i + 1 < len(entries) else VEH_STRIDE
    if t in ("string", "embedded"):
        n = max(1, nxt - off)
        lines.append(f"    {ctype} {name}[0x{n:X}];  // 0x{off:04X} {trust}")
        cursor = off + n
    else:
        sz = SIZE.get(t, 4)
        lines.append(f"    {ctype} {name};  // 0x{off:04X} {trust}")
        cursor = off + sz

if cursor < VEH_STRIDE:
    lines.append(f"    uint8_t gap_{cursor:04X}[0x{VEH_STRIDE - cursor:X}];")

lines.append("};")
lines.append("")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")

# --- IDA variant: drop the #include, respell types ---
ida_lines = []
for ln in lines:
    if ln.startswith("#"):
        continue
    for c_t, ida_t in IDA_TYPE.items():
        # only respell the leading type token of a member declaration
        if ln.startswith(f"    {c_t} "):
            ln = f"    {ida_t} " + ln[len(f"    {c_t} "):]
            break
    ida_lines.append(ln)
open(OUT_IDA, "w", encoding="utf-8").write("\n".join(ida_lines) + "\n")

print(f"{len(entries)} fields, {gap_n} gaps")
print(f"  C   -> {OUT}")
print(f"  IDA -> {OUT_IDA}")
print(f"sizeof(F1CVehicle) should be 0x{VEH_STRIDE:X} ({VEH_STRIDE})")
