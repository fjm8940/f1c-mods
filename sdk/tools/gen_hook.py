DETOUR_NOTES = """
## Detour checklist
1. Open 0x{addr:08x} in Ghidra/IDA; confirm the calling convention and the
   real argument list — fix `target_t` and `hook()` to match (see the docs
   entry for {label}).
2. Set `PROLOGUE_LEN` to a whole-instruction boundary ≥ 5. Wrong length = crash.
3. `g_trampoline(...)` runs the original; omit it to fully replace behavior.
"""


def write_project(name, files):
    d = os.path.join(MODS_DIR, name)
    os.makedirs(d, exist_ok=True)
    for fn, content in files.items():
        with open(os.path.join(d, fn), 'w', encoding='utf-8') as f:
            f.write(content)
    print(f"  scaffolded mods/{name}/ :")
    for fn in files:
        print(f"    {fn}")
    print(f"  build: cd mods/{name} && build.bat")


def main():
    args = sys.argv[1:]
    if len(args) < 2:
        print(__doc__)
        return
    template, name = args[0], args[1]
    desc = ' '.join(args[3:]) if len(args) > 3 and args[2].startswith('--') else \
           f"{template} mod"
    sdk = load_sdk()

    if template == 'tick':
        files = {
            f"{name}.c": TICK_C.format(name=name, desc=desc),
            "build.bat": BUILD_BAT.format(name=name, mingw=MINGW),
            "README.md": README.format(name=name, desc=desc, template="tick",
                                       tgt="", mingw=MINGW, detour_notes=""),
        }
        write_project(name, files)
    elif template == 'detour':
        if len(args) < 3:
            sys.exit("detour needs a target: gen_hook.py detour <name> <addr|funcname>")
        addr, label = resolve_func(load_functions(), args[2])
        files = {
            f"{name}.c": DETOUR_C.format(name=name, desc=desc, addr=addr, label=label),
            "build.bat": BUILD_BAT.format(name=name, mingw=MINGW),
            "README.md": README.format(
                name=name, desc=desc, template="detour",
                tgt=f" targeting `{label}` (0x{addr:08x})", mingw=MINGW,
                detour_notes=DETOUR_NOTES.format(addr=addr, label=label)),
        }
        write_project(name, files)
        print(f"  target: {label} @ 0x{addr:08x} — verify PROLOGUE_LEN + signature")
    else:
        sys.exit(f"unknown template '{template}' (use: tick | detour)")


if __name__ == '__main__':
    main()
