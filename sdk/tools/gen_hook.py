"""
gen_hook.py — scaffold a DLL mod wired to the F1C SDK.

Produces a compilable mods/<name>/ project (DLL source + build.bat + README)
in the proven red_flag.dll style (MinGW32, absolute VAs, no ASLR). The mod
becomes "fill in one C function body".

Two templates:

  tick   — per-frame polling thread. Best for: watch a state, poke globals,
           implement logic that runs continuously (virtual safety car, dynamic
           weather). No binary modification; pure external logic.
             python tools/gen_hook.py tick vsc

  detour — inline-hook a game function: your code runs, then optionally calls
           the original. Best for: intercept a specific event/decision.
             python tools/gen_hook.py detour my-penalty 0x004bc0e0
             python tools/gen_hook.py detour my-penalty DisqualificationHandler

Addresses/names resolve through mods/sdk/f1c_sdk.json (run gen_sdk.py first).
Detour uses a 5-byte relative JMP + a heap trampoline holding the overwritten
prologue bytes; you must set PROLOGUE_LEN to a whole-instruction boundary
(the scaffold prints how to find it and defaults to 5 with a loud TODO).
"""

import json
import os
import re
import sys

if sys.platform == 'win32':
    sys.stdout.reconfigure(encoding='utf-8', errors='replace')

import glob

PROJ_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
# IDA corpus: SDK lives in tools/sdk/ (built by tools/gen_sdk_from_index.py)
SDK_JSON = os.path.join(os.path.dirname(os.path.abspath(__file__)), "sdk", "f1c_sdk.json")
FUNCTIONS_DIR = os.path.join(PROJ_ROOT, "functions")
MODS_DIR = os.path.join(PROJ_ROOT, "mods")
MINGW = r"C:\msys64\mingw32\bin"


def load_sdk():
    try:
        with open(SDK_JSON, encoding='utf-8') as f:
            return json.load(f)
    except FileNotFoundError:
        sys.exit("tools/sdk/f1c_sdk.json missing — run: python tools/gen_sdk_from_index.py")


def load_functions():
    """IDA corpus function index: {name: addr_int} from functions/<Name>_<8hex>.c.

    The corpus SDK json exports globals/vehicle fields, not functions; the
    canonical named-function list is the functions/ directory itself.
    """
    funcs = {}
    for p in glob.glob(os.path.join(FUNCTIONS_DIR, "*.c")):
        base = os.path.basename(p)[:-2]              # drop '.c'
        m = re.match(r'^(.*)_([0-9a-fA-F]{6,8})$', base)
        if m:
            funcs[m.group(1)] = int(m.group(2), 16)
    if not funcs:
        sys.exit(f"no functions found in {FUNCTIONS_DIR}")
    return funcs


def resolve_func(funcs, token):
    """name or 0xADDR -> (addr_int, label)"""
    if re.match(r'(?:0x)?[0-9a-fA-F]{6,8}$', token):
        addr = int(token, 16)
        for n, a in funcs.items():
            if a == addr:
                return addr, n
        return addr, f'sub_{addr:08x}'
    if token in funcs:
        return funcs[token], token
    matches = [n for n in funcs if token.lower() in n.lower()]
    if len(matches) == 1:
        return funcs[matches[0]], matches[0]
    if matches:
        print(f"ambiguous '{token}':")
        for n in matches[:15]:
            print(f"  {n}  0x{funcs[n]:08x}")
        sys.exit(1)
    sys.exit(f"unknown function '{token}'")


